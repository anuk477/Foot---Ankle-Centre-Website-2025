// Run with Playwright available in NODE_PATH and a PHP preview at FAC_TEST_URL.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const base = process.env.FAC_TEST_URL || 'http://127.0.0.1:8765';
const output = process.env.FAC_TEST_OUTPUT || path.join(require('node:os').tmpdir(), 'fac-assistant-review');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.FAC_TEST_BROWSER || undefined });
  const context = await browser.newContext({ viewport: { width: 1280, height: 900 } });
  // Never submit to a real inbox or contact external services from these tests.
  await context.route('**/*', route => new URL(route.request().url()).origin === new URL(base).origin ? route.continue() : route.abort());
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.addInitScript(() => { window.turnstile = { getResponse: () => 'test-token', reset() {} }; });
  await page.goto(base + '/');
  await page.getByRole('button', { name: 'Help with appointments' }).click();
  await page.locator('.fac-retry').waitFor({ state: 'visible' });
  assert.equal(await page.getByRole('textbox', { name: 'Your appointment question' }).isVisible(), true);
  assert.equal(await page.getByRole('button', { name: 'Help me choose an appointment', exact: true }).count(), 0);
  await page.getByRole('textbox', { name: 'Your appointment question' }).fill('Which appointment should I request?');
  await page.locator('.fac-compose button').click();
  await page.getByText('Your message has not been sent', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Clear chat' }).click();
  await page.locator('.fac-panel').screenshot({ path: path.join(output, 'desktop-chat.png') });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.fac-panel').isVisible(), false);
  assert.equal(await page.locator('.fac-launch').evaluate(el => el === document.activeElement), true);
  await page.locator('.fac-launch').click();
  await page.getByRole('button', { name: 'Appointment guide', exact: true }).click();
  await page.getByRole('button', { name: 'Help me choose an appointment', exact: true }).click();
  await page.getByRole('button', { name: /^Podiatry Appointment/ }).click();
  await page.getByRole('button', { name: 'Chingford', exact: true }).click();
  await page.locator('.fac-preferences [name=date]').fill('2099-10-20');
  await page.locator('.fac-preferences [name=preferredTime]').fill('After 3pm');
  await page.getByRole('button', { name: 'Continue to request form' }).click();
  await page.waitForURL('**/booking?service=*');
  const form = page.locator('form[data-form-type=booking]');
  await page.locator('[data-assistant-handoff]').waitFor({ state: 'visible' });
  assert.equal(await form.locator('[name=service]').inputValue(), 'Podiatry Appointment');
  assert.equal(await form.locator('[name=location]').inputValue(), 'Chingford');
  assert.equal(await form.locator('[name=date]').inputValue(), '2099-10-20');
  assert.equal(await form.locator('[name=preferredTime]').inputValue(), 'After 3pm');
  assert.equal(await page.evaluate(() => sessionStorage.getItem('fac-appointment-preferences')), null);
  await form.locator('[name=name]').fill('Test Patient');
  await form.locator('[name=email]').fill('test@example.invalid');
  await form.locator('[name=phone]').fill('020 7946 0123');
  await form.locator('[name=existingPatient][value=yes]').check();
  await form.locator('[name=notes]').fill('Test only — do not send.');
  let captured;
  await page.route('https://script.google.com/macros/**', route => {
    captured = new URLSearchParams(route.request().postData());
    return route.fulfill({ status: 200, body: 'Mock accepted' });
  });
  await page.route('https://www.footandanklecentre.co.uk/success/', route => route.fulfill({ status: 200, body: 'Mock success navigation' }));
  await form.getByRole('button', { name: 'Send appointment request' }).click();
  await page.waitForURL('https://www.footandanklecentre.co.uk/success/');
  assert.equal(captured.get('date'), '2099-10-20');
  assert.equal(captured.get('notes'), 'Preferred time: After 3pm\n\nTest only — do not send.');
  assert.equal(captured.get('service'), 'Podiatry Appointment');

  await page.goto(base + '/booking');
  await page.locator('.fac-launch').click();
  await page.getByRole('button', { name: 'Appointment guide', exact: true }).click();
  await page.getByRole('button', { name: 'Help me choose an appointment', exact: true }).click();
  await page.getByRole('button', { name: 'I’m not sure — ask reception' }).click();
  await page.getByRole('button', { name: 'No preference', exact: true }).click();
  await page.getByRole('button', { name: 'Continue to request form' }).click();
  assert.equal(await form.locator('[name=service]').inputValue(), 'Not sure — please advise');
  assert.equal(await form.locator('[name=location]').inputValue(), 'No preference');
  assert.equal(await form.locator('[name=date]').inputValue(), '');
  assert.equal(await form.locator('[name=preferredTime]').inputValue(), '');

  let aiError = false, urgent = false, posted;
  await page.route('**/api/assistant.php', route => {
    if (route.request().method() === 'GET') return route.fulfill({ json: { enabled: true, csrf: 'test-csrf' } });
    posted = route.request().postDataJSON();
    if (aiError) return route.fulfill({ status: 503, json: { ok: false } });
    return route.fulfill({ json: { ok: true, message: urgent ? 'For medical help now, call NHS 111. Call 999 in a life-threatening emergency.' : '<img src=x onerror=alert(1)> Reception will confirm your request.', service: urgent ? '' : 'Podiatry Appointment', links: ['prices', 'invalid-link'], urgent } });
  });
  await page.goto(base + '/blog/centrolock-mis-bunion-surgery-under-local-anaesthetic/');
  await page.locator('.fac-launch').click();
  await page.locator('.fac-consent').waitFor({ state: 'visible' });
  assert.equal(await page.getByRole('textbox', { name: 'Your appointment question' }).isDisabled(), false);
  await page.getByRole('textbox', { name: 'Your appointment question' }).fill('What are your fees?');
  await page.locator('.fac-compose button').click();
  assert.equal(posted, undefined);
  assert.equal(await page.getByRole('textbox', { name: 'Your appointment question' }).inputValue(), 'What are your fees?');
  await page.getByText('Please tick the agreement above', { exact: false }).waitFor();
  await page.locator('.fac-consent input').check();
  const ask = async text => {
    await page.getByRole('textbox', { name: 'Your appointment question' }).fill(text);
    await page.locator('.fac-compose button').click();
    await page.waitForFunction(() => !document.querySelector('.fac-compose button').disabled);
  };
  await ask('Can you explain podiatry appointments?');
  assert.equal(posted.consent, true); assert.equal(posted.history.length, 0);
  assert.equal(await page.locator('.fac-assistant img').count(), 0);
  assert.equal(await page.locator('.fac-link').first().getAttribute('href'), base + '/prices/');
  await page.getByRole('button', { name: 'Request: Podiatry Appointment' }).waitFor();
  urgent = true; await ask('I need medical help now');
  await page.getByRole('link', { name: 'Call NHS 111' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Browse appointment options' }).count(), 0);
  urgent = false; aiError = true; await ask('Another appointment question');
  await page.getByText('AI replies are unavailable right now.', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Clear chat' }).click();
  assert.equal(await page.locator('.fac-consent input').isChecked(), false);
  assert.equal(await page.locator('.fac-message-user').count(), 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('.fac-panel').screenshot({ path: path.join(output, 'mobile-chat.png') });
  const box = await page.locator('.fac-panel').boundingBox();
  assert.ok(box.x >= 0 && box.x + box.width <= 390 && box.y >= 0 && box.y + box.height <= 844);
  await page.getByRole('button', { name: 'Appointment guide', exact: true }).click();
  await page.getByRole('button', { name: 'Help me choose an appointment', exact: true }).click();
  await page.getByRole('button', { name: /^Physiotherapy/ }).click();
  await page.getByRole('button', { name: 'Wanstead', exact: true }).click();
  await page.locator('.fac-preferences [name=date]').fill('2000-01-01');
  assert.equal(await page.locator('.fac-preferences').evaluate(el => el.checkValidity()), false);
  await page.locator('.fac-preferences [name=date]').fill('2099-10-20');
  await page.locator('.fac-panel').screenshot({ path: path.join(output, 'mobile-preferences.png') });
  assert.deepEqual(errors, []);
  console.log('PASS: guided flow, same-page and cross-page handoff, optional preferences, past dates, request payload, nested URLs, AI consent, text rendering, urgent actions, API failure, reset, keyboard and mobile bounds.');
  console.log('Screenshots: ' + output);
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
